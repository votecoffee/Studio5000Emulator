    def test_rate_diagnostics_preserve_level_alarms_and_recover_after_overflow(self):
        e = self.engine()
        m = e.memory
        alarm = m.read(ALARM)
        m.write('PressureAlarm.ROCPeriod', 32768)
        m.write('PressureAlarm.ROCPosLimit', -100)
        m.write('PressureAlarm.ROCNegLimit', -100)
        m.write('PressureAlarm.MinDurationPRE', 0)
        m.write('Pressure', -3e38)
        e.step()
        self.assertEqual(alarm['Status'], 0b11100001)
        for name in ('ROCPosLimitInv', 'ROCNegLimitInv', 'ROCPeriodInv'):
            self.assertTrue(m.read(f'{ALARM}.{name}'))
        self.assertTrue(alarm['LLInAlarm'])
        m.write('PressureAlarm.ROCPeriod', 0.01)
        m.write('PressureAlarm.ROCPosLimit', 100)
        m.write('PressureAlarm.ROCPosSeverity', 1001)
        e.step()
        self.assertEqual(alarm['Status'], 0b01000101)
        m.write('PressureAlarm.ROCNegLimit', 100)
        m.write('PressureAlarm.ROCPosSeverity', 500)
        m.write('Pressure', 3e38)
        e.step()
        self.assertTrue(m.read('PressureAlarm.Overflow'))
        self.assertTrue(m.read('PressureAlarm.InstructFault'))
        self.assertTrue(alarm['HHInAlarm'])
        self.assertFalse(alarm['ROCPosInAlarm'])
        self.assertEqual(alarm['ROC'], 0.0)
        e.step(5)
        self.assertTrue(m.read('PressureAlarm.Overflow'))
        e.step(5)
        self.assertEqual(alarm['Status'], 0)
        self.assertTrue(alarm['HHInAlarm'])

    def test_conditions_expire_independently_and_rearm_only_when_active(self):
        e = self.engine()
        m = e.memory
        alarm = m.read(ALARM)
        m.write('PressureAlarm.MinDurationPRE', 0)
        m.write('Pressure', 90)
        e.step()
        m.write('PressureAlarm.HHOperShelve', True)
        m.write('PressureAlarm.HHOperAck', True)
        e.step()
        self.assertTrue(alarm['HHShelved'])
        self.assertTrue(alarm['HHAcked'])
        self.assertTrue(alarm['HInAlarmUnack'])
        m.write('PressureAlarm.ShelveDuration', 2)
        m.write('PressureAlarm.HOperShelve', True)
        m.write('PressureAlarm.HOperAck', True)
        e.step()
        m.write('Pressure', 50)
        e.step()
        m.write('Pressure', 90)
        e.step(59_979)
        self.assertTrue(alarm['HHShelved'])
        self.assertTrue(alarm['HHAcked'])
        self.assertTrue(alarm['HAcked'])
        self.assertEqual((alarm['HAlarmCount'], alarm['HHAlarmCount']), (2, 2))
        e.step(1)
        self.assertFalse(alarm['HHShelved'])
        self.assertTrue(alarm['HHInAlarmUnack'])
        self.assertTrue(alarm['HShelved'])
        self.assertTrue(alarm['HAcked'])
        m.write('Pressure', 50)
        e.step(60_000)
        e.step(10)
        self.assertFalse(alarm['HShelved'])
        self.assertTrue(alarm['HAcked'])

    def test_unshelve_precedence_and_reshelf_use_per_condition_edges(self):
        e = self.engine()
        m = e.memory
        alarm = m.read(ALARM)
        m.write('PressureAlarm.ROCPeriod', 0.01)
        m.write('PressureAlarm.ROCPosLimit', 100)
        m.write('Pressure', 50)
        e.step()
        m.write('PressureAlarm.HOperShelve', True)
        m.write('PressureAlarm.ROCPosOperShelve', True)
        m.write('PressureAlarm.HOperUnshelve', True)
        m.write('Pressure', 51)
        e.step()
        self.assertFalse(alarm['HShelved'])
        self.assertTrue(alarm['ROCPosShelved'])
        self.assertTrue(alarm['ROCPosInAlarm'])
        self.assertTrue(alarm['ROCPosAcked'])
        self.assertFalse(alarm['HOperUnshelve'])
        m.write('PressureAlarm.HOperShelve', True)
        e.step()
        self.assertFalse(alarm['HShelved'])
        m.write('PressureAlarm.ProgUnshelveAll', True)
        m.write('PressureAlarm.ROCPosOperShelve', True)
        e.step()
        self.assertFalse(alarm['ROCPosShelved'])
        self.assertTrue(alarm['ProgUnshelveAll'])
        m.write('PressureAlarm.ProgUnshelveAll', False)
        m.write('PressureAlarm.ROCPosOperShelve', True)
        e.step()
        self.assertFalse(alarm['ROCPosShelved'])
        e.step()
        m.write('PressureAlarm.MaxShelveDuration', 1)
        m.write('PressureAlarm.ShelveDuration', 5)
        m.write('PressureAlarm.ROCPosOperShelve', True)
        e.step()
        e.step(30_000)
        m.write('PressureAlarm.ROCPosOperShelve', True)
        e.step()
        e.step(59_999)
        self.assertTrue(alarm['ROCPosShelved'])
        self.assertEqual(alarm['ShelveDuration'], 5)
        e.step(1)
        self.assertFalse(alarm['ROCPosShelved'])

    def test_suppression_and_false_rung_defer_shelf_rearming(self):
        e = self.engine()
        m = e.memory
        alarm = m.read(ALARM)
        m.write('PressureAlarm.MinDurationPRE', 0)
        m.write('Pressure', 90)
        e.step()
        m.write('PressureAlarm.HOperShelve', True)
        m.write('PressureAlarm.HOperAck', True)
        e.step()
        m.write('AnalogRun', False)
        m.write('PressureAlarm.OperSuppress', True)
        e.step(60_000)
        self.assertTrue(alarm['HShelved'])
        self.assertTrue(alarm['OperSuppress'])
        m.write('AnalogRun', True)
        e.step()
        self.assertFalse(alarm['HShelved'])
        self.assertTrue(alarm['HAcked'])
        self.assertTrue(alarm['Suppressed'])
        m.write('PressureAlarm.OperUnsuppress', True)
        e.step()
        self.assertTrue(alarm['HInAlarmUnack'])
        m.write('PressureAlarm.HOperShelve', True)
        e.step()
        self.assertTrue(alarm['HShelved'])
        m.write('PressureAlarm.HOperUnshelve', True)
        e.enter_run()
        self.assertFalse(alarm['HShelved'])
        self.assertFalse(alarm['HOperUnshelve'])
        self.assertEqual(alarm['HAlarmCount'], 1)

    def test_late_fault_restores_level_rate_and_shelf_state(self):
        def configure(controller):
            tags = controller.find('Tags')
            for name in ('Divisor', 'Quotient'):
                tag = ET.SubElement(tags, 'Tag', Name=name, TagType='Base', DataType='DINT')
                ET.SubElement(ET.SubElement(tag, 'Data', Format='Decorated'),
                              'DataValue', DataType='DINT', Value='1')
            content = controller.find('.//RLLContent')
            ET.SubElement(ET.SubElement(content, 'Rung', Number='3', Type='N'),
                          'Text').text = 'DIV(1,Divisor,Quotient);'
        e = self.engine(configure)
        m = e.memory
        m.write('PressureAlarm.ROCPeriod', 0.01)
        m.write('PressureAlarm.ROCPosLimit', 100)
        m.write('Pressure', 50)
        e.step()
        m.write('Pressure', 95)
        m.write('PressureAlarm.ROCPosOperShelve', True)
        m.write('Divisor', 0)
        prior = copy.deepcopy((m.values, e.last_timer, e.time_ms, e.scan_count))
        with self.assertRaisesRegex(ModelError, '(?i)divide|division'):
            e.step()
        self.assertEqual((m.values, e.last_timer, e.time_ms, e.scan_count), prior)
        m.write('Divisor', 1)
        e.step()
        self.assertTrue(m.read('PressureAlarm.ROCPosInAlarm'))
        self.assertEqual(m.read('PressureAlarm.ROCPosInAlarmCount'), 1)
        self.assertTrue(m.read('PressureAlarm.ROCPosShelved'))
        self.assertFalse(m.read('PressureAlarm.ROCPosOperShelve'))
        e.step()
        self.assertFalse(m.read('PressureAlarm.HInAlarm'))
        e.step()
        self.assertEqual(m.read('PressureAlarm.HAlarmCount'), 1)

    def test_import_checks_real_fields_and_processor_profile(self):
        for value in ('true', '1e100'):
            def configure(controller):
                controller.find('.//AlarmAnalogParameters').set('HHLimit', value)
            with self.subTest(value=value):
                self.assertIn('ALARM_ANALOG.HHLimit', ' '.join(self.engine(configure, check=False).blockers))
        old = self.engine(lambda c: c.set('ProcessorType', '1756-L75'), check=False)
        self.assertIn('ALARM_ANALOG storage requires', ' '.join(old.blockers))


